/**
 * Эталонные данные жестов для сравнения с MediaPipe Hands.
 * Каждый жест содержит 21 точку руки (x, y, z) в нормализованных координатах [0..1].
 *
 * Формат одной точки: [x, y, z]
 *   x, y — позиция в кадре (0..1)
 *   z — глубина (меньше = ближе к камере)
 *
 * Индексы пальцев MediaPipe:
 *   0  — запястье (wrist)
 *   1–4  — большой палец (CMC, MCP, IP, TIP)
 *   5–8  — указательный (MCP, PIP, DIP, TIP)
 *   9–12 — средний
 *   13–16 — безымянный
 *   17–20 — мизинец
 */

// Вспомогательная функция — создать 21 точку с шумом ±0.02
function refWithNoise(base, noise = 0.02) {
  return base.map(p => [
    p[0] + (Math.random() - 0.5) * noise,
    p[1] + (Math.random() - 0.5) * noise,
    p[2] + (Math.random() - 0.5) * noise * 0.5,
  ]);
}

